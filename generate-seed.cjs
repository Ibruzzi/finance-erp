// generate-seed.cjs
const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const INPUT_DIR = path.resolve(__dirname, 'import-files');
const OUTPUT_FILE = path.resolve(__dirname, 'src', 'db', 'seedData.js');

const allRows = [];
const yearCounts = {};

if (!fs.existsSync(INPUT_DIR)) {
  console.error(`❌ Error: Folder not found: ${INPUT_DIR}`);
  process.exit(1);
}

const files = fs.readdirSync(INPUT_DIR).filter(f => f.endsWith('.xlsx'));
console.log(`Found ${files.length} .xlsx files.`);

files.forEach(file => {
  console.log(`Processing ${file}...`);
  const workbook = XLSX.readFile(path.join(INPUT_DIR, file));
  
  workbook.SheetNames.forEach(sheetName => {
    const sheet = workbook.Sheets[sheetName];
    const rows = XLSX.utils.sheet_to_json(sheet, { defval: null, raw: true });

    rows.forEach(row => {
      // Normalize keys to lowercase to handle both 'Date' and 'date', 'amount_original' and 'Amount'
      const getVal = (key) => {
        if (row[key] !== undefined) return row[key];
        const lowerKey = key.toLowerCase();
        const actualKey = Object.keys(row).find(k => k.toLowerCase() === lowerKey);
        return actualKey ? row[actualKey] : null;
      };

      const dateVal = getVal('date');
      const category = getVal('category');
      const subcategory = getVal('subcategory');
      // Check 'amount_original' first, then 'amount'
      const amount = getVal('amount_original') !== null ? getVal('amount_original') : getVal('amount');
      const currency = getVal('currency') || 'MVR';
      const notes = getVal('notes') || '';

      if (!dateVal || !category || amount === undefined || amount === null || amount === 0) return;

      // Handle Excel Serial Numbers (e.g., 44931) vs Date Strings (e.g., '2023-01-05')
      let parsedDate;
      if (typeof dateVal === 'number') {
        // Excel epoch starts at 1899-12-30
        const excelEpoch = new Date(Date.UTC(1899, 11, 30));
        parsedDate = new Date(excelEpoch.getTime() + dateVal * 24 * 60 * 60 * 1000);
      } else {
        parsedDate = new Date(dateVal);
      }

      if (isNaN(parsedDate.getTime())) return;

      // Convert to local ISO date string safely
      const isoDate = parsedDate.toISOString();
      const year = parsedDate.getFullYear();
      
      yearCounts[year] = (yearCounts[year] || 0) + 1;

      const type = String(category).toLowerCase().includes('income') ? 'Income' : 'Expense';
      
      const rate = String(currency).toUpperCase() === 'USD' ? 15.42 : 1;
      const amount_mvr = Number(amount) * rate;

      // Default bucket mapping
      let bucket = 'Discretionary';
      if (type === 'Income') bucket = 'Income';
      else if (['Bills', 'Medical', 'Tickets', 'Transportation', 'Grocery', 'Samu', 'General', 'Water', 'Electricity', 'Food', 'Rent', 'Bappa'].includes(subcategory)) bucket = 'Essential';
      else if (['Debt', 'Pension', 'Zakat', 'Loan Repayment'].includes(subcategory)) bucket = 'Financial/Obligatory';

      allRows.push({
        date: isoDate,
        category: String(category).trim(),
        subcategory: String(subcategory || '').trim(),
        amount_original: Number(amount),
        currency: String(currency).toUpperCase(),
        exchange_rate_at_time: rate,
        amount_mvr,
        type,
        bucket,
        is_historical: true,
        notes: String(notes).trim()
      });
    });
  });
});

const uniqueRows = Array.from(new Set(allRows.map(r => JSON.stringify(r)))).map(s => JSON.parse(s));

const fileContent = `// Auto-generated by generate-seed.cjs\n// Do not edit directly\nexport const SEED_DATA = ${JSON.stringify(uniqueRows, null, 2)};\n`;
fs.writeFileSync(OUTPUT_FILE, fileContent);

console.log(`\n✅ Successfully generated seedData.js with ${uniqueRows.length} rows!`);
console.log('Breakdown by year:', yearCounts);
